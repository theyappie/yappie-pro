// Builds tools/admin/worker.js, the single file to paste into a Cloudflare Worker.
// It joins src/worker-main.js, the shared rules in scripts/admin.mjs, and the two pages (src/login.html, src/app.html).
// Run it after changing any of those:  node tools/admin/build.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url)), root = join(here, "..", "..");
const read = p => readFileSync(join(here, p), "utf8");

const core = readFileSync(join(root, "scripts", "admin.mjs"), "utf8");
// the shared rules without their "export" keywords, so they can sit inside the Worker and inside the dashboard page
const stripExports = src => {
  if (/^\s*import\s/m.test(src)) throw new Error("scripts/admin.mjs must not import anything");
  return src.replace(/^export (const|function|class) /gm, "$1 ");
};
const coreBody = stripExports(core);
if (/^\s*export\s/m.test(coreBody)) throw new Error("scripts/admin.mjs has an export form the build does not handle");

// the core also goes inside a <script> element, where "<!--" and "</script" would confuse the HTML parser
const coreForPage = coreBody.replaceAll("<!--", "<\\!--");
if (/<\/script/i.test(coreForPage)) throw new Error("scripts/admin.mjs contains </script");

const login = read("src/login.html"), app = read("src/app.html").replace("{{CORE}}", () => coreForPage);
for (const [n, t] of [["login.html", login], ["app.html", app]]) if (/<\/script\s*>\s*<\/script/i.test(t)) throw new Error(n + " looks wrong");

let main = read("src/worker-main.js");
const imp = /^import \{[^}]*\} from "\.\.\/\.\.\/\.\.\/scripts\/admin\.mjs";\r?\n/m;
if (!imp.test(main)) throw new Error("worker-main.js: the import of scripts/admin.mjs was not found");
main = main.replace(imp, "");
if (/^import\s/m.test(main)) throw new Error("worker-main.js has another import");

const out = `// The Yappie Pro admin: one Cloudflare Worker (login page, dashboard and API).
// GENERATED by tools/admin/build.mjs from tools/admin/src and scripts/admin.mjs. Do not edit this file; edit the sources and build again.
// Setup: tools/admin/README.md

// ---- shared rules (scripts/admin.mjs) ----
${coreBody}
// ---- pages ----
const UI = { login: ${JSON.stringify(login)}, app: ${JSON.stringify(app)} };

// ---- Worker ----
${main}`;
writeFileSync(join(here, "worker.js"), out);
console.log(`tools/admin/worker.js written (${(out.length / 1024).toFixed(0)} KB).`);
